using Ueci.Unreal;
using System.Text.Json;

namespace Ueci.Plugin;

public sealed record UnrealPluginHostLayout(
    string Root,
    string ProjectPath,
    string PluginRoot,
    string PluginDescriptorPath,
    string GameTargetName,
    string EditorTargetName);

public static class UnrealPluginHostProject
{
    public const string GameTargetName = "UECIHost";
    public const string EditorTargetName = "UECIHostEditor";

    public static async Task<UnrealPluginHostLayout> PrepareAsync(
        string engineRoot,
        UnrealPluginDescriptor plugin,
        CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(engineRoot);
        ArgumentNullException.ThrowIfNull(plugin);

        string workspace = Path.Combine(
            Path.GetFullPath(engineRoot), ".ueci", "plugin-work", Sanitize(plugin.Name));
        string pluginRoot = Path.Combine(workspace, "Plugins", plugin.Name);
        if (Directory.Exists(workspace))
        {
            Directory.Delete(workspace, recursive: true);
        }
        Directory.CreateDirectory(pluginRoot);

        string sourcePluginRoot = Path.GetDirectoryName(plugin.DescriptorPath)
            ?? throw new InvalidDataException("Unable to determine plugin source directory.");
        CopyDirectory(sourcePluginRoot, pluginRoot, relative: string.Empty);

        string copiedDescriptor = Path.Combine(pluginRoot, Path.GetFileName(plugin.DescriptorPath));
        string projectPath = Path.Combine(workspace, "UECIHost.uproject");
        await WriteProjectAsync(projectPath, plugin.Name, cancellationToken).ConfigureAwait(false);
        await WriteHostSourceAsync(workspace, cancellationToken).ConfigureAwait(false);
        await WriteBuildConfigurationAsync(engineRoot, workspace, cancellationToken).ConfigureAwait(false);

        return new UnrealPluginHostLayout(
            workspace,
            projectPath,
            pluginRoot,
            copiedDescriptor,
            GameTargetName,
            EditorTargetName);
    }

    private static async Task WriteProjectAsync(
        string path,
        string pluginName,
        CancellationToken cancellationToken)
    {
        var payload = new
        {
            FileVersion = 3,
            Category = "UECI",
            Description = "Ephemeral host project generated by UECI.",
            Modules = new[]
            {
                new
                {
                    Name = GameTargetName,
                    Type = "Runtime",
                    LoadingPhase = "Default",
                },
            },
            Plugins = new[] { new { Name = pluginName, Enabled = true } },
        };
        string json = JsonSerializer.Serialize(payload, new JsonSerializerOptions { WriteIndented = true });
        await File.WriteAllTextAsync(path, json + Environment.NewLine, cancellationToken).ConfigureAwait(false);
    }

    private static async Task WriteHostSourceAsync(string workspace, CancellationToken cancellationToken)
    {
        string source = Path.Combine(workspace, "Source");
        string module = Path.Combine(source, GameTargetName);
        Directory.CreateDirectory(module);

        await File.WriteAllTextAsync(
            Path.Combine(source, GameTargetName + ".Target.cs"),
            $$"""
            using UnrealBuildTool;

            public class {{GameTargetName}}Target : TargetRules
            {
                public {{GameTargetName}}Target(TargetInfo Target) : base(Target)
                {
                    // UECI's runtime host is intentionally a standalone Program target. A Game
                    // target implicitly enables Engine/developer-tool surfaces (Launch,
                    // TargetPlatform, shader/texture formats, etc.) which are unrelated to a
                    // Core-only plugin and massively inflate the lazy working set.
                    Type = TargetType.Program;
                    LinkType = TargetLinkType.Monolithic;
                    LaunchModuleName = "{{GameTargetName}}";
                    DefaultBuildSettings = BuildSettingsVersion.Latest;
                    IncludeOrderVersion = EngineIncludeOrderVersion.Latest;

                    bCompileAgainstEngine = false;
                    bCompileAgainstCoreUObject = false;
                    bCompileAgainstApplicationCore = false;
                    bBuildDeveloperTools = false;
                    bBuildTargetDeveloperTools = false;
                    bForceBuildTargetPlatforms = false;
                    bForceBuildShaderFormats = false;
                    bNeedsExtraShaderFormatsOverride = false;
                    bCompileWithPluginSupport = true;
                    bIncludePluginsForTargetPlatforms = true;
                    bAllowEnginePluginsEnabledByDefault = false;
                    bUsesSlate = false;
                    bCompileICU = false;
                    bEnableTrace = false;

                    ExtraModuleNames.Add("{{GameTargetName}}");
                }
            }
            """ + Environment.NewLine,
            cancellationToken).ConfigureAwait(false);

        await File.WriteAllTextAsync(
            Path.Combine(source, EditorTargetName + ".Target.cs"),
            $$"""
            using UnrealBuildTool;

            public class {{EditorTargetName}}Target : TargetRules
            {
                public {{EditorTargetName}}Target(TargetInfo Target) : base(Target)
                {
                    Type = TargetType.Editor;
                    DefaultBuildSettings = BuildSettingsVersion.Latest;
                    IncludeOrderVersion = EngineIncludeOrderVersion.Latest;
                    ExtraModuleNames.Add("{{GameTargetName}}");
                }
            }
            """ + Environment.NewLine,
            cancellationToken).ConfigureAwait(false);

        await File.WriteAllTextAsync(
            Path.Combine(module, GameTargetName + ".Build.cs"),
            $$"""
            using UnrealBuildTool;

            public class {{GameTargetName}} : ModuleRules
            {
                public {{GameTargetName}}(ReadOnlyTargetRules Target) : base(Target)
                {
                    PrivateDependencyModuleNames.Add("Core");
                }
            }
            """ + Environment.NewLine,
            cancellationToken).ConfigureAwait(false);

        await File.WriteAllTextAsync(
            Path.Combine(module, GameTargetName + ".cpp"),
            "#include \"Modules/ModuleManager.h\"\nIMPLEMENT_MODULE(FDefaultModuleImpl, UECIHost)\n",
            cancellationToken).ConfigureAwait(false);
    }

    private static async Task WriteBuildConfigurationAsync(
        string engineRoot,
        string workspace,
        CancellationToken cancellationToken)
    {
        // UE 5.8 still evaluates both UBA switches when selecting an executor.
        // bAllowUBALocalExecutor is deprecated, but leaving it at its default can still
        // cause ExecutorFactory to pre-create UBA before platform/toolchain validation.
        // Write the same policy at Engine and Project scope; UnrealBuildToolRunner also
        // writes it into UECI's isolated user profile before every invocation.
        string[] directories =
        [
            Path.Combine(Path.GetFullPath(engineRoot), "Engine", "Saved", "UnrealBuildTool"),
            Path.Combine(workspace, "Saved", "UnrealBuildTool"),
        ];

        foreach (string directory in directories)
        {
            await UnrealBuildToolConfiguration.WriteHermeticLocalExecutorAsync(
                directory,
                cancellationToken).ConfigureAwait(false);
        }
    }

    private static void CopyDirectory(string sourceRoot, string destinationRoot, string relative)
    {
        string source = relative.Length == 0 ? sourceRoot : Path.Combine(sourceRoot, relative);
        string destination = relative.Length == 0 ? destinationRoot : Path.Combine(destinationRoot, relative);
        Directory.CreateDirectory(destination);

        foreach (string file in Directory.EnumerateFiles(source))
        {
            File.Copy(file, Path.Combine(destination, Path.GetFileName(file)), overwrite: true);
        }

        foreach (string directory in Directory.EnumerateDirectories(source))
        {
            string name = Path.GetFileName(directory);
            if (name is "Intermediate" or "Saved" or ".git" or ".ueci")
            {
                continue;
            }
            if (relative.Length == 0 && name == "Binaries")
            {
                string thirdParty = Path.Combine(directory, "ThirdParty");
                if (Directory.Exists(thirdParty))
                {
                    CopyDirectory(sourceRoot, destinationRoot, Path.Combine("Binaries", "ThirdParty"));
                }
                continue;
            }
            string child = relative.Length == 0 ? name : Path.Combine(relative, name);
            CopyDirectory(sourceRoot, destinationRoot, child);
        }
    }

    private static string Sanitize(string value)
    {
        char[] invalid = Path.GetInvalidFileNameChars();
        string sanitized = new(value.Select(character => invalid.Contains(character) ? '_' : character).ToArray());
        return string.IsNullOrWhiteSpace(sanitized) ? "Plugin" : sanitized;
    }
}
